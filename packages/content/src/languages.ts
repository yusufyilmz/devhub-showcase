export const getPortfolioCopy = (
  language: Language = "en",
): PortfolioMessages => messages[language];
export function formatPortfolioPeriod(
  start: Date | string,
  end: Date | string | null,
  language: Language = "en",
) {
  const formatter = new Intl.DateTimeFormat(language, {
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  });
  return `${formatter.format(new Date(start))} - ${end ? formatter.format(new Date(end)) : getPortfolioCopy(language).present}`;
}
